import { z } from 'zod';
import { MILESTONE_TYPES, MilestoneType } from '../domain/workflow';

const isoDate = z.coerce.date();

export const CreateShipmentBody = z.object({
  organizationId: z.string().uuid(),
  bookingReference: z.string().max(64).optional(),
  blNumber: z.string().max(64).optional(),
  shippingLine: z.string().max(128).optional(),
  vesselName: z.string().max(128).optional(),
  voyageNumber: z.string().max(32).optional(),
  originPort: z.string().min(2).max(64),
  originTerminal: z.string().max(64).optional(),
  destinationCountry: z.string().min(2).max(64),
  destinationCity: z.string().min(2).max(64),
  deliveryAddress: z.string().max(256).optional(),
  cargoDescription: z.string().max(512).optional(),
  packageCount: z.number().int().positive().optional(),
  grossWeightKg: z.number().positive().optional(),
  plannedVesselArrival: isoDate.optional(),
  currentEta: isoDate.optional(),
  routeCode: z.string().optional(),
  assignedAgentUserId: z.string().uuid().optional(),
  containers: z
    .array(
      z.object({
        containerNumber: z.string().min(11).max(16),
        sizeType: z.string().max(32).optional(),
        freeDays: z.number().int().min(0).max(60).optional(),
      }),
    )
    .min(1, 'Add at least one container.'),
});
export type CreateShipmentBody = z.infer<typeof CreateShipmentBody>;

export const RecordMilestoneBody = z.object({
  type: z.enum(MILESTONE_TYPES as [MilestoneType, ...MilestoneType[]]),
  containerId: z.string().uuid().optional(),
  eventAt: isoDate.optional(),
  location: z.string().max(128).optional(),
  notes: z.string().max(2000).optional(),
  reasonCode: z.string().max(64).optional(),
  visibility: z.enum(['client', 'internal']).default('client'),
  data: z.record(z.string(), z.union([z.string(), z.number(), z.boolean()])).default({}),
  evidenceDocumentIds: z.array(z.string().uuid()).default([]),
  /** Generated by the app per submission; a retry with the same key is ignored. */
  idempotencyKey: z.string().min(8).max(128),
  overrideReason: z.string().max(500).optional(),
});
export type RecordMilestoneBody = z.infer<typeof RecordMilestoneBody>;

export const AssignTruckBody = z.object({
  containerIds: z.array(z.string().uuid()).min(1).max(2),
  truckRegistration: z.string().min(2).max(32),
  trailerRegistration: z.string().max(32).optional(),
  driverUserId: z.string().uuid().optional(),
  driverName: z.string().min(2).max(128),
  driverPhone: z.string().max(32).optional(),
  transporterName: z.string().max(128).optional(),
  plannedLoadingAt: isoDate.optional(),
  borderCrossing: z.string().max(64).optional(),
  idempotencyKey: z.string().min(8).max(128),
});
export type AssignTruckBody = z.infer<typeof AssignTruckBody>;

export const ReviseEtaBody = z.object({
  eta: isoDate,
  reason: z.string().min(3).max(200),
  notes: z.string().max(1000).optional(),
});
export type ReviseEtaBody = z.infer<typeof ReviseEtaBody>;

export const CorrectEventBody = z.object({
  eventAt: isoDate,
  reason: z.string().min(3).max(500),
});
export type CorrectEventBody = z.infer<typeof CorrectEventBody>;

export const CloseShipmentBody = z.object({
  overrideReason: z.string().max(500).optional(),
});
export type CloseShipmentBody = z.infer<typeof CloseShipmentBody>;
